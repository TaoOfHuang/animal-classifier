/** 界门纲目科属的合并视图（与前端 COMMON_* 常量同源并扩充） */
export const RANK_ZH: Record<string, string> = {
  ...KINGDOM_ZH,
  ...PHYLUM_ZH,
  ...CLASS_ZH,
  ...ORDER_ZH,
  ...FAMILY_ZH,
  ...GENUS_ZH,
};

/** 学名 → 层级，用于给任意学名标注它在七级中的位置 */
export const RANK_LEVEL_OF: Record<string, TaxonomyLevel> = (() => {
  const map: Record<string, TaxonomyLevel> = {};
  const groups: Array<[TaxonomyLevel, Record<string, string>]> = [
    ['kingdom', KINGDOM_ZH],
    ['phylum', PHYLUM_ZH],
    ['class', CLASS_ZH],
    ['order', ORDER_ZH],
    ['family', FAMILY_ZH],
    ['genus', GENUS_ZH],
  ];
  for (const [level, group] of groups) {
    for (const scientificName of Object.keys(group)) {
      map[scientificName.toUpperCase()] = level;
    }
  }
  return map;
})();

const RANK_ZH_UPPER = new Map(
  Object.entries(RANK_ZH).map(([k, v]) => [k.toUpperCase(), v]),
);

const SPECIES_ZH_UPPER = new Map(
  Object.entries(SPECIES_ZH).map(([k, v]) => [k.toUpperCase(), v]),
);

/** 查界/门/纲/目/科/属译名，未收录返回 undefined（大小写不敏感） */
export const getRankNameZh = (scientificName: string): string | undefined =>
  RANK_ZH_UPPER.get(scientificName.trim().toUpperCase());

/** 查种级中文名，未收录返回 undefined（大小写不敏感） */
export const getSpeciesNameZh = (scientificName: string): string | undefined =>
  SPECIES_ZH_UPPER.get(scientificName.trim().toUpperCase());

/** 学名 → 层级，基础词典之外的学名返回 undefined（可用词数兜底推断） */
export const getRankLevelOf = (scientificName: string): TaxonomyLevel | undefined =>
  RANK_LEVEL_OF[scientificName.trim().toUpperCase()];

/**
 * 统一入口：先查种，再查属及以上的译名，都没有则**回退学名本身**。
 * 绝不返回空串，也绝不用 LLM 臆造中文名。
 */
export const getCommonNameZh = (scientificName: string): string => {
  const trimmed = scientificName.trim();
  if (!trimmed) {
    return trimmed;
  }
  return getSpeciesNameZh(trimmed) ?? getRankNameZh(trimmed) ?? trimmed;
};
